#include <iostream>
#include <algorithm>
#include <vector>

const int RUN = 8; // Размер мини-блока для эффективных вставок

// 1. Сортировка вставками на локальном отрезке памяти [left, right]
void insertionSort(int arr[], int left, int right) {
    for (int i = left + 1; i <= right; i++) {
        int key = arr[i]; // Прячем карту в карман
        int j = i - 1;
        
        // Сдвигаем элементы стопки вправо, пока они больше ключа
        while (j >= left && arr[j] > key) {
            arr[j + 1] = arr[j]; // Освобождаем место (сдвиг вправо)
            j--;
        }
        arr[j + 1] = key; // Вставляем карту из кармана
    }
}

// 2. Стабильное слияние двух отсортированных кусков: left ... mid и mid+1 ... right
void merge(int arr[], int l, int m, int r) {
    int len1 = m - l + 1; // Точная длина левого куска
    int len2 = r - m;     // Точная длина правого куска
    
    // Создаем временные буферы
    std::vector<int> left(len1), right(len2);

    // Копируем данные во временные массивы
    for (int i = 0; i < len1; i++) left[i] = arr[l + i];
    for (int i = 0; i < len2; i++) right[i] = arr[m + 1 + i];

    int i = 0, j = 0, k = l;
    
    // Каретки бегут по буферам и сшивают их в исходный arr
    while (i < len1 && j < len2) {
        if (left[i] <= right[j]) { // Знак <= гарантирует стабильность сортировки
            arr[k++] = left[i++];
        } else {
            arr[k++] = right[j++]; // Берем элемент из правого буфера
        }
    }
    
    // Сбрасываем оставшиеся хвосты
    while (i < len1) arr[k++] = left[i++];
    while (j < len2) arr[k++] = right[j++];
}

// Управляющий каркас Timsort
void timSort(int arr[], int n) {
    // Шаг 1: Нарезаем массив на Runs длиной по 8 элементов и выпрямляем их Вставками
    for (int i = 0; i < n; i += RUN) {
        int right_border = std::min((i + RUN - 1), (n - 1));
        insertionSort(arr, i, right_border);
    }

    // Шаг 2: Итеративно сшиваем Runs слиянием (размер удваивается: 8 -> 16 -> 32...)
    // Для текущего размера массива, условие size < n = False, поэтому этот блок скипается
    for (int size = RUN; size < n; size = 2 * size) {
        for (int left = 0; left < n; left += 2 * size) {
            int mid = left + size - 1; // Конец первого подмассива
            int right = std::min((left + 2 * size - 1), (n - 1)); // Конец второго подмассива

            // Старт слияния, только если есть второй кусок для сшивания
            if (mid < right) {
                merge(arr, left, mid, right);
            }
        }
    }
}

int main() {
    int arr[] = {64, 34, 25, 12, 22, 11, 90, 7};

    // Логика простая: размер массива в байтах делим на размер одного элемента в байтах,
    // получаем количество элементов в массиве, которое передаем в timSort.
    // Это нужно, чтобы при изменении размера массива не менять каждый раз его длину вручную.
    int n = sizeof(arr) / sizeof(arr[0]);
    timSort(arr, n);

    // Познавательно было увидеть разницу между простым принтом и выводом в потоке, в дебаггере.
    std::cout << "Sorted array: ";
    for (int i = 0; i < n; i++) {
        std::cout << arr[i] << " ";
    }
    std::cout << std::endl;

    return 0;
}